// @ts-expect-error - Node.js built-in modules
import { resolve, join } from 'path'
// @ts-expect-error - Node.js built-in modules
import { promises as fs } from 'fs'
import { defineNuxtModule, addTemplate, addImports, addTypeTemplate } from 'nuxt/kit'

export default defineNuxtModule({
    meta: {
        name: 'nuxt-i18n-dynamic-imports',
        configKey: 'i18nDynamicImports',
    },
    defaults: {
        localesDir: 'i18n/locales',
        outputFileName: 'i18n-dynamic-imports',
    },
    async setup(options, nuxt) {
        const localesPath = resolve(nuxt.options.srcDir, options.localesDir)

        async function scanLocaleFiles(): Promise<Record<string, string[]>> {
            const structure: Record<string, string[]> = {}

            try {
                const locales = await fs.readdir(localesPath)

                for (const locale of locales) {
                    const localePath = join(localesPath, locale)
                    const stat = await fs.stat(localePath)

                    if (stat.isDirectory()) {
                        const localeFiles = await fs.readdir(localePath)
                        structure[locale] = localeFiles
                            .filter((file: string) => file.endsWith('.json') && file !== 'common.json')
                            .map((file: string) => file.replace('.json', ''))
                    }
                }
            }
            catch (error) {
                console.error('Failed to scan locales:', error)
            }

            return structure
        }

        function generateImportMap(structure: Record<string, string[]>): string {
            // 生成映射对象
            const entries = Object.entries(structure)
                .map(([locale, namespaces]) => {
                    const namespaceEntries = namespaces
                        .map(
                            ns => `    "${ns}": ()=>{
                    const modules = import.meta.glob('~/${options.localesDir}/${locale}/${ns}.json', { eager: true, import: 'default' })
                    return modules['/${options.localesDir}/${locale}/${ns}.json']
                }`,
                        )
                        .join(',\n')
                    return `  "${locale}": {\n${namespaceEntries}\n  }`
                })
                .join(',\n')

            return `
export const i18nImportMap = {\n${entries}\n}`
        }

        function generateTypeDefinitions(structure: Record<string, string[]>): string {
            const localeTypes = Object.entries(structure).map(([locale, namespaces]) => {
                const namespaceTypes = namespaces.map(ns => `    "${ns}": ()=>Record<string, any>`).join('\n')
                return `  "${locale}": {\n${namespaceTypes}\n  }`
            }).join('\n')

            return `// Auto-generated by nuxt-i18n-dynamic-imports
            // Do not edit this file manually

            export interface I18nImportMap {
            ${localeTypes}
            }

            declare global {
            const i18nImportMap: I18nImportMap
            }

            export {}
        `
        }

        async function updateTemplates() {
            const structure = await scanLocaleFiles()
            const importMapContent = generateImportMap(structure)
            const typeDefinitions = generateTypeDefinitions(structure)

            addTemplate({
                filename: `${options.outputFileName}.mjs`,
                getContents: () => importMapContent,
                write: true,
            })

            addTypeTemplate({
                filename: `${options.outputFileName}.d.ts`,
                getContents: () => typeDefinitions,
            })
            addImports({
                name: 'i18nImportMap',
                from: `#build/${options.outputFileName}.mjs`,
            })
        }

        // 在准备阶段生成模板
        await updateTemplates()

        if (nuxt.options.dev) {
            nuxt.hook('builder:watch', async (event, path) => {
                if (path.includes(options.localesDir) && path.endsWith('.json')) {
                    console.log(`[i18n Dynamic] 文件${event}: ${path}`)
                    await updateTemplates()
                }
            })

            // 添加 Vite HMR 处理
            nuxt.hook('vite:extendConfig', (config, { isClient }) => {
                if (!isClient)
                    return

                config.plugins = config.plugins || []
                config.plugins.push({
                    name: 'i18n-hmr-handler',
                    handleHotUpdate: async ({ file, server }) => {
                        // 检查是否是 i18n 文件
                        if (file.includes('i18n/locales') && file.endsWith('.json')) {
                            console.log(`[i18n HMR] 检测到语言文件变化: ${file}`)

                            // 提取语言代码和命名空间
                            const match = file.match(/i18n\/locales\/([^/]+)\/([^/]+)\.json/)
                            const locale = match?.[1]
                            const namespace = match?.[2]

                            await updateTemplates()

                            // 发送自定义 HMR 事件到所有客户端
                            server.ws.send({
                                type: 'custom',
                                event: 'i18n-update',
                                data: {
                                    file,
                                    locale,
                                    namespace,
                                    timestamp: Date.now(),
                                },
                            })

                            console.log(`[i18n HMR] 已推送更新事件: ${locale}/${namespace}`)

                            // 返回空数组，阻止默认的 HMR 行为
                            return []
                        }
                    },
                })
            })
        }
    },
})
